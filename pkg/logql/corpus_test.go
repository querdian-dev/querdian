package logql

// The corpus is written by hand from the public LogQL documentation (and the
// black-box findings in docs/research/logql.md, which cite the same pages).
// Every case names the page its construct comes from. Examples are adapted,
// not copied verbatim, where the docs use placeholders.

const (
	docQuery   = "https://grafana.com/docs/loki/latest/query/"
	docLog     = "https://grafana.com/docs/loki/latest/query/log_queries/"
	docMetric  = "https://grafana.com/docs/loki/latest/query/metric_queries/"
	docExample = "https://grafana.com/docs/loki/latest/query/query_examples/"
	docRef     = "https://grafana.com/docs/loki/latest/query/query_reference/"
)

type corpusCase struct {
	url  string
	kind QueryKind
	q    string
}

var corpus []corpusCase

func add(url string, kind QueryKind, qs ...string) {
	for _, q := range qs {
		corpus = append(corpus, corpusCase{url, kind, q})
	}
}

